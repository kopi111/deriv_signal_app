import 'package:flutter/material.dart';

import '../domain/playbook.dart';
import 'desk_theme.dart';

/// What this exact strategy did on data it was never tuned on.
class TrackRecord extends StatelessWidget {
  const TrackRecord({super.key, required this.entry});

  final PlaybookEntry entry;

  @override
  Widget build(BuildContext context) {
    final result = entry.outOfSample;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        _Verdict(entry: entry),
        const SizedBox(height: 14),
        Wrap(
          spacing: 24,
          runSpacing: 14,
          children: [
            _Figure('Trades', '${result.trades}'),
            _Figure('Win rate', '${(result.winRate * 100).toStringAsFixed(0)}%'),
            _Figure('Profit factor', result.profitFactor.toStringAsFixed(2)),
            _Figure('Avg per trade', '${_signed(result.expectancyR)}R'),
            _Figure('Total', '${_signed(result.totalR)}R'),
            _Figure('Worst drawdown', '-${result.maxDrawdownR.toStringAsFixed(1)}R'),
          ],
        ),
        const SizedBox(height: 14),
        Text(
          'Walk-forward test, ${entry.testedFrom} to ${entry.testedTo}, ${entry.timeframe} candles, '
          'spread charged on every trade. Profitable in ${entry.positiveFolds} of ${entry.foldCount} '
          'test periods. Random entries with the same stop and target did as well '
          '${(entry.randomBeatShare * 100).toStringAsFixed(0)}% of the time. '
          'Untouched final period: ${_signed(entry.lockbox.totalR)}R over ${entry.lockbox.trades} trades.',
          style: DeskType.body(14, color: DeskColors.muted),
        ),
      ],
    );
  }

  static String _signed(double value) =>
      '${value >= 0 ? '+' : ''}${value.toStringAsFixed(value.abs() >= 10 ? 0 : 2)}';
}

class _Verdict extends StatelessWidget {
  const _Verdict({required this.entry});

  final PlaybookEntry entry;

  @override
  Widget build(BuildContext context) {
    final color = entry.proven ? DeskColors.buy : DeskColors.waiting;
    final headline = entry.proven ? 'Passed every test' : 'No proven edge';
    final detail = entry.proven
        ? 'Profitable on unseen data, consistent across periods, and beat random entries.'
        : entry.isSynthetic
            ? 'Deriv synthetic indices are generated by a random number generator. '
                'Why unproven: ${entry.failedChecks.join('; ')}. Trade small, or not at all.'
            : 'Why unproven: ${entry.failedChecks.join('; ')}. Treat signals as ideas, not instructions.';
    return Container(
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        border: Border(left: BorderSide(color: color, width: 3)),
        color: color.withValues(alpha: 0.08),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(headline, style: DeskType.display(22, color: color)),
          const SizedBox(height: 4),
          Text(detail, style: DeskType.body(14)),
        ],
      ),
    );
  }
}

class _Figure extends StatelessWidget {
  const _Figure(this.label, this.value);

  final String label;
  final String value;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(value, style: DeskType.display(26)),
        Text(label, style: DeskType.body(13, color: DeskColors.muted)),
      ],
    );
  }
}
